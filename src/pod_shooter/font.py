class PixelFont:
    """Renders text using line-drawn pixel glyphs — no pygame.font needed."""

    def __init__(self, _name, size):
        self.scale = max(1, size / 7)
        self.glyph_w = int(5 * self.scale)
        self.glyph_h = int(7 * self.scale)
        self.spacing = int(1 * self.scale)

    def render(self, text, _antialias=True, color=(255, 255, 255)):
        text = text.upper()
        total_w = len(text) * (self.glyph_w + self.spacing)
        surf = pygame.Surface((max(1, total_w), self.glyph_h + int(self.scale)),
                              pygame.SRCALPHA)
        x_off = 0
        for ch in text:
            segs = _GLYPHS.get(ch, [])
            for (x1, y1), (x2, y2) in segs:
                sx1 = x_off + int(x1 * self.scale)
                sy1 = int(y1 * self.scale)
                sx2 = x_off + int(x2 * self.scale)
                sy2 = int(y2 * self.scale)
                w = max(1, int(self.scale * 0.6))
                pygame.draw.line(surf, color, (sx1, sy1), (sx2, sy2), w)
            x_off += self.glyph_w + self.spacing
        return surf
